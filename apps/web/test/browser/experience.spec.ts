import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test.use({ viewport: { width: 1296, height: 800 }, launchOptions: { args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] } })
test('welcome and unavailable access follow the spatial design, with guest entry independent of 3D', async ({ page }) => {
  await page.route('**/assets/models/walle/walle.glb', route => route.fulfill({ status: 503 }))
  await page.goto('/')
  const guest = page.getByRole('link', { name: 'Comenzar como invitado' })
  await expect(guest).toHaveAttribute('href', '/mundo')
  await expect(page.getByText('No pudimos cargar el personaje.')).toBeVisible()
  await expect(guest).toBeEnabled()
  await page.getByRole('link', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Acceso no disponible' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Principal' })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Seguir como invitado' })).toHaveAttribute('href', '/mundo')
  await page.getByRole('button', { name: 'Volver a la bienvenida' }).click()
  await expect(page.getByRole('link', { name: 'Iniciar sesión', exact: true })).toBeFocused()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('link', { name: 'Iniciar sesión', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
})

test('opening access from the world retains its canvas and camera and blocks movement until return', async ({ page }) => {
  test.setTimeout(120000)
  await page.addInitScript(() => localStorage.setItem('mimix-onboarding-v2', 'seen'))
  await page.goto('/mundo')
  await expect(page.locator('#world-loading')).toHaveCount(0, { timeout: 90000 })
  await expect(page.locator('#play-state-announcement')).toContainText('Mundo listo')
  await page.locator('#canvas').evaluate(canvas => { (canvas as HTMLElement).dataset.retained = 'yes' })
  await page.getByRole('link', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Acceso y cuenta MIMIX' })).toBeVisible()
  const readView = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('mimix.world-view.v1')!).view)
  const before = await readView()
  await page.keyboard.press('KeyW')
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL(/\/mundo$/)
  await expect(page.locator('#canvas')).toHaveAttribute('data-retained', 'yes')
  await expect(page.getByRole('link', { name: 'Iniciar sesión', exact: true })).toBeFocused()
  await page.getByRole('link', { name: 'Iniciar sesión', exact: true }).click()
  expect((await readView()).position).toEqual(before.position)
  await page.getByRole('button', { name: 'Volver al mundo' }).click()
  await expect(page).toHaveURL(/\/mundo$/)
  await page.reload()
  await expect(page.locator('#world-loading')).toHaveCount(0, { timeout: 90000 })
  await page.getByRole('link', { name: 'Iniciar sesión', exact: true }).click()
  expect((await readView()).position).toEqual(before.position)
})

