import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test.skip(process.env.MIMIX_AUTH_SMOKE !== '1', 'Requires the existing Clerk development fixture accounts and a real local Clerk environment.')
test('native Clerk verification, wrong code, account and sign-out keep the spatial experience', async ({ page }) => {
  test.setTimeout(120000)
  await page.setViewportSize({ width: 1296, height: 800 })
  await page.goto('/')
  await expect(page.getByRole('link', { name: 'Comenzar como invitado' })).toBeVisible()
  await page.screenshot({ path: 'test-results/experience-home-desktop.png' })
  await page.getByRole('link', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Accede a MIMIX' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continuar con Google' })).toBeVisible()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'test-results/experience-access-desktop.png' })
  await page.getByRole('textbox', { name: 'Correo electrónico', exact: true }).fill('mimix-alice+clerk_test@example.com')
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Verifica tu correo' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/experience-verify-mobile.png', fullPage: true })
  await page.getByRole('textbox', { name: 'Enter verification code' }).fill('000000')
  await expect(page.getByText('El código ingresado es incorrecto.').first()).toBeVisible()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
  await page.screenshot({ path: 'test-results/experience-code-error-mobile.png', fullPage: true })
  await page.getByRole('textbox', { name: 'Enter verification code' }).fill('424242')
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('link', { name: 'Continuar', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/experience-home-signed-mobile.png' })
  await page.getByRole('link', { name: 'Mi cuenta', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Mi cuenta', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Administrar cuenta' })).toBeVisible()
  await page.screenshot({ path: 'test-results/experience-account-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Administrar cuenta' }).click()
  await expect(page.getByRole('heading', { name: 'Cuenta', exact: true }).first()).toBeVisible()
  await page.screenshot({ path: 'test-results/experience-profile-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Close modal', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Administrar cuenta' })).toBeFocused()
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('link', { name: 'Comenzar como invitado' })).toBeVisible()
})

test('native sign-in returns to the educational world and preserves its view', async ({ page }) => {
  test.setTimeout(120000)
  await page.addInitScript(() => localStorage.setItem('mimix-onboarding-v2', 'seen'))
  await page.goto('/mundo')
  await expect(page.locator('#play-state-announcement')).toContainText('Mundo listo', { timeout: 90000 })
  await page.getByRole('link', { name: 'Iniciar sesión', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Accede a MIMIX' })).toBeVisible()
  const readView = () => page.evaluate(() => JSON.parse(sessionStorage.getItem('mimix.world-view.v1')!).view)
  const before = await readView()
  // A full navigation also exercises recovery of the validated origin and view.
  await page.reload()
  await page.getByRole('textbox', { name: 'Correo electrónico', exact: true }).fill('mimix-alice+clerk_test@example.com')
  await page.getByRole('button', { name: 'Continuar', exact: true }).click()
  await page.getByRole('textbox', { name: 'Enter verification code' }).fill('424242')
  await expect(page).toHaveURL(/\/mundo$/)
  await expect(page.locator('#play-state-announcement')).toContainText('Mundo listo', { timeout: 90000 })
  await page.getByRole('link', { name: 'Mi cuenta', exact: true }).click()
  expect((await readView()).position).toEqual(before.position)
  expect((await readView()).camera).toEqual(before.camera)
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click()
  await expect(page).toHaveURL(/\/mundo$/)
  await expect(page.getByRole('link', { name: 'Iniciar sesión', exact: true })).toBeVisible()
})
